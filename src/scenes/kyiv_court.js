// Киев, площадка у шахматных столов (сценарное ТЗ, разделы 5–8 и «Правки владельца 03.10.2026»). Слева направо: вход из парка → шахматный стол со скамьями (Димасик сидит справа от стола, пока идёт
// партия) → стойка «ІГРИ В ПАРКУ» и слева от неё Илюшкинс (supply) → низкое ограждение с открытой калиткой (fence) → половина площадки Алеси (до strip1) → барьер посередине (net: невидимая стена,
// пропускает снаряды; сетки как картинки нет, границу показывает центральная линия разметки) → половина Димасика (field0 … field1: он ходит по ней весь бой) и его стойка с гантелями (rack) →
// проём в живой изгороди (gap), куда он уходит после боя → машина Uber (car). Проводы у машины идут сами (сценарий): состояние машины для рисования — sc.taxi = { dx, door }.
// Площадка увеличена (владелец 09.10.2026: «увеличить площадку… чтобы наш персонаж не просто стоял на самом левом краю, а Димасик в другом краю; увеличить поле, на котором Димасик стоит»):
// раньше зона боя (Илюшкинс … Димасик) была 850 юн. и помещалась в самый узкий вид, у Алеси было 460 юн. полосы, у Димасика — шаг 860↔920 (60 юн.). Теперь половина Алеси 600 юн. (fence … strip1),
// поле Димасика 510 юн. (field0 … field1), вся зона от Илюшкинса до дальнего края поля — 1455 юн. (1,7× прежней). Камера в бою едет за обоими (kyiv_story.js, court: camFrame), а Димасик держится
// не дальше 830 юн. от героини (dimasik.js, FIELD.hard), поэтому на любом виде от 1000 юн. оба в кадре, пока она на площадке (у стойки, когда он у барьера, — с узкими полями). Снаряды Димасика долетают и за стойку (до reach, на 160…260 юн. за ней):
// у Илюшкинса не спрятаться (в лёгком режиме — по-прежнему останавливаются у ограждения). Из зоны пополнения (слева от ограждения) атаковать нельзя, вернуться к Илюшкинсу можно всегда
// (ограждение — открытая калитка, не стена). Барьер после победы открывается (и на время ухода Димасика от шахмат). Подробно — docs/DIMASIK_FIGHT.md.
(function () {
  'use strict';
  const Ale = (window.Ale = window.Ale || {});
  const A = Ale.Art;
  // Расстановка (владелец, 03.10.2026): Димасик сидит ПЕРЕД площадкой за шахматным столом (chess; стол со скамьями — на переднем плане, герои проходят за ним), играют, он уходит к себе на площадку;
  // Илюшкинс в бою стоит слева от стойки с оружием (supply), не заслоняя её и лицом к бою; Бубел — вплотную справа от него (bubel; штанга и диск долетают и туда: она подпрыгивает, как он); после победы Димасик уходит в проём
  // живой изгороди (gap), а машина Uber (car) стоит целиком на виду.
  const FY = 600, WALL = 584, WIDTH = 3260, X0 = 1000;

  const X = (Ale.KYIV_COURT = {
    X0, width: WIDTH,
    start: 480,                                    // вход из парка (правее левой группы экранных кнопок)
    chess: 640, seat: 718, seatLeft: 562,          // шахматный стол, место Димасика (справа от стола, лицом влево) и пустая скамья слева
    supply: X0 + 70, stand: X0 + 200, fence: X0 + 310,
    bubel: X0 + 126,                               // пост Бубела в бою: вплотную справа от Илюшкинса (supply + 56), перед левым краем стойки: в кадре она всегда, когда в кадре он (владелец 09.10.2026: «где-то рядом с Илюшкинсом»)
    reach: X0 - 60,                                // докуда долетают штанга и диск (левый край предмета): 260 юн. за серединой стойки, 160 — за её левым краем
    strip1: X0 + 910, net: X0 + 945,               // правый предел половины Алеси (её центр не правее) и барьер посередине площадки (невидимая стена шириной 28)
    field0: X0 + 990, field1: X0 + 1500,           // поле Димасика: где может стоять его центр в бою
    dimIntro: X0 + 1030,                           // где он стоит во время речи перед боем и в начале каждой попытки (подошёл к барьеру)
    rack: X0 + 1580,                               // его стойка с гантелями — за дальней торцевой линией
    gap: X0 + 1700,                                // проём в живой изгороди: Димасик уходит вглубь парка
    car: X0 + 1960,                                // машина Uber (бывшее такси)
    lineL: X0 + 366, lineR: X0 + 1540,             // разметка площадки: торцевые линии (центральная — на барьере)
  });

  Ale.Scenes.kyivCourt = function (game, entry) {
    const sc = new Ale.Scene(game, { id: 'kyivCourt', width: WIDTH, music: Ale.Audio.pick('kyiv_park', 'paris'), place: entry === 'start' ? Ale.T.place.kyivCourt : null });
    const W = sc.world;
    W.addSolid(-400, FY, WIDTH + 800, 400, { kind: 'floor' });
    W.addSolid(-400, -400, 400, 1500);
    W.addSolid(WIDTH, -400, 400, 1500);
    sc.net = W.addSolid(X.net - 14, -400, 28, 1000, { kind: 'net', passProjectile: true });          // барьер посередине площадки: невидимая стена (держит и Алесю, и Димасика), снаряды проходят (сетку убрали по просьбе владельца; граница — центральная линия разметки)
    sc.taxi = { dx: 0, door: 0 };                                  // состояние машины Uber для оформления: смещение (уезжает вправо) и открытость задней двери 0…1

    const KA = Ale.KyivArt, layers = KA.courtLayers(game, WIDTH, X);
    sc.back.push((ctx, cam) => KA.courtBack(ctx, cam, game, sc, layers));
    sc.front.push((ctx) => A.vignette(ctx, game.viewW, game.viewH, 0.24));

    // ---- оформление: стойка с наборами, ограждение (калитка открыта), шахматный стол со скамьями (на переднем плане), стойка с гантелями, кусты справа, машина Uber
    for (const d of KA.courtDecor(X, sc)) sc.add(new Ale.Decor({ x: d.x, y: FY, z: d.z, draw: (ctx, self) => d.draw(ctx, sc.time) }));
    // Стол и обе скамьи рисуются одним спрайтом выше героев (z = 58, kyiv_art_park.js), передняя грань правой скамьи — его часть. Сценарий по-прежнему опускает sc.benchFront.z до 40, когда Димасик встал
    // (раньше это была отдельная деталь): пустая деталь принимает присваивание и ничего не меняет — можно убрать вместе с этими двумя строками сценария.
    sc.benchFront = sc.add(new Ale.Decor({ x: X.seat, y: FY, z: 58, draw: () => {} }));

    // ---- герои
    const p = sc.add(new Ale.Player({ x: X.start, y: FY, facing: 1 }));
    sc.player = p;
    sc.bubel = sc.add(new Ale.Bubel({ x: X.start - 70, y: FY, facing: 1 }));
    sc.ilya = sc.add(new Ale.Person({ kind: 'ilyushkins', x: X.start + 70, y: FY, facing: 1, id: 'ilyushkinsSupply' }));
    sc.actors.ilyushkins = sc.ilya;                                // реплики Илюшкинса (говорящий — «ilyushkins») тянутся к нему же
    sc.dim = sc.add(new Ale.Dimasik({ x: X.dimIntro, y: FY, facing: -1, arena: { fence: X.fence, reach: X.reach, strip1: X.strip1, field0: X.field0, field1: X.field1 } }));
    for (const d of KA.courtFront(X)) sc.add(new Ale.Decor({ x: d.x, y: FY, z: d.z, draw: (ctx) => d.draw(ctx, sc.time) }));

    Ale.KyivStory.court(sc, entry);
    return sc;
  };
})();
